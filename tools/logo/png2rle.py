"""
Turn assets/logo.png into a C header for the bootloader (h2boot), which shows
the logo while it loads the kernel: a palette and run-length pairs (count,
palette index), a few KB instead of 150. bootloader/build.sh runs it.

    python3 tools/logo/png2rle.py logo.png fathom-logo.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from png2ppm import read_png  # noqa: E402


def main(src, dst):
    w, h, rows = read_png(src)
    palette, index, runs = [], {}, []
    for px in rows:
        for i in range(0, len(px), 3):
            c = (px[i] << 16) | (px[i + 1] << 8) | px[i + 2]
            if c not in index:
                index[c] = len(palette)
                palette.append(c)
            k = index[c]
            if runs and runs[-1][1] == k and runs[-1][0] < 255:
                runs[-1][0] += 1
            else:
                runs.append([1, k])
    assert len(palette) <= 256
    data = [b for r in runs for b in r]
    with open(dst, 'w') as f:
        f.write('/* Generated by tools/logo/png2rle.py from assets/logo.png: do not edit. */\n')
        f.write('#define FATHOM_LOGO_W %d\n#define FATHOM_LOGO_H %d\n' % (w, h))
        f.write('static const unsigned long fathom_logo_palette[%d] = {\n' % len(palette))
        for i in range(0, len(palette), 8):
            f.write('    ' + ', '.join('0x%06x' % c for c in palette[i:i + 8]) + ',\n')
        f.write('};\n/* (count, palette index) pairs, row after row */\n')
        f.write('static const unsigned char fathom_logo_rle[%d] = {\n' % len(data))
        for i in range(0, len(data), 16):
            f.write('    ' + ','.join(str(b) for b in data[i:i + 16]) + ',\n')
        f.write('};\n')
    print('%s: %d colours, %d runs, %d bytes' % (dst, len(palette), len(runs), len(data)))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit('usage: png2rle.py logo.png fathom-logo.h')
    main(sys.argv[1], sys.argv[2])
