# AAC for Bluetooth headphones, built by you, for your own H2 (see README.md):
#
#   docker/run.sh tools/bluetooth-aac/build.sh
#
# Builds bluez-alsa with Fraunhofer's FDK AAC encoder in its own Buildroot
# tree (/cache/br-h2-aac: it needs a C++ toolchain, which Fathom's build
# doesn't have), with Fathom's architecture and toolchain settings, and puts
# the two files the card needs in build/bt-aac/. Copy that folder to the card
# as fathom/bt-aac. Rebuild it after updating Fathom: it uses Fathom's own
# Bluetooth libraries (fathom/bt), which must be the same versions.
set -eu
out=/cache/br-h2-aac
cfg=/work/build/bt-aac.defconfig
mkdir -p /work/build
{
    echo "# Generated by tools/bluetooth-aac/build.sh from Fathom's defconfig"
    grep -E '^BR2_(mips|TOOLCHAIN_BUILDROOT_MUSL|SHARED_STATIC_LIBS|PACKAGE_HOST_LINUX_HEADERS|CCACHE)' \
        /work/buildroot/external/configs/fathom_h2_defconfig
    cat <<CFG
BR2_DL_DIR="/cache/dl"
BR2_INIT_NONE=y
BR2_SYSTEM_BIN_SH_NONE=y
BR2_TOOLCHAIN_BUILDROOT_CXX=y
BR2_PACKAGE_DBUS=y
BR2_PACKAGE_BLUEZ5_UTILS=y
BR2_PACKAGE_BLUEZ5_UTILS_PLUGINS_AUDIO=y
BR2_PACKAGE_BLUEZ_ALSA=y
BR2_PACKAGE_FDK_AAC=y
BR2_PACKAGE_LIBFREEAPTX=y
CFG
} > "$cfg"
# BR2_EXTERNAL: Fathom's libfreeaptx, so this bluealsa keeps aptX (external.mk)
make -C /work/buildroot/buildroot O="$out" BR2_EXTERNAL=/work/buildroot/external \
    BR2_DEFCONFIG="$cfg" defconfig > /dev/null
make -C "$out" bluez-alsa-dirclean     # configured afresh: its options follow Fathom's
make -C "$out"

d=/work/build/bt-aac
rm -rf "$d"
mkdir -p "$d"
strip=$(ls "$out"/host/bin/*-linux-*strip | head -1)
cp -L "$out/target/usr/bin/bluealsa" "$d/bluealsa"
cp -L "$out/target/usr/lib/libfdk-aac.so.2" "$d/libfdk-aac.so.2"
"$strip" --strip-unneeded "$d/bluealsa" "$d/libfdk-aac.so.2"
cp "$(ls -d "$out"/build/fdk-aac-*/ | head -1)NOTICE" "$d/FDK-AAC-NOTICE.txt"
cat > "$d/README.txt" <<TXT
AAC for Fathom's Bluetooth: bluez-alsa built with the Fraunhofer FDK AAC
encoder, for your own use. Copy this folder to the card as fathom/bt-aac;
fathom-bt uses it when it's there. Not part of Fathom's releases: see
tools/bluetooth-aac/README.md in Fathom's source.
TXT
ls -la "$d"
echo "AAC add-on: build/bt-aac/ (copy to the card as fathom/bt-aac)"
