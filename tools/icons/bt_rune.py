"""
The header's Bluetooth icon: the plain rune (no box), anti-aliased, as an A8
image the UI tints with the theme's colour. Sized and placed like the header's
other symbols (Montserrat 14: a 16 px line, baseline 13 px down; pause and
shuffle are 13 px tall, from 1 px below the baseline up), so it sits level with
them.

    python3 tools/icons/bt_rune.py app/ui/bt_rune.h      (and prints a preview)
"""
import math
import sys

W, H = 11, 16           # the image: the line's height
TOP, BOTTOM = 1.0, 14.0  # the rune's extent: rows 1-13, like a 13 px glyph
R = 0.72                # half the stroke width
SS = 8                  # supersampling per axis

cx = W / 2
xl, xr = 1.0 + R + 0.35, W - 1.0 - R - 0.35
ya = TOP + (BOTTOM - TOP) * 0.27
yb = TOP + (BOTTOM - TOP) * 0.73
# the rune, as one stroke: lower arm in, up to the top, down to the bottom, upper arm out
PATH = [(xl, ya), (xr, yb), (cx, BOTTOM - R), (cx, TOP + R), (xr, ya), (xl, yb)]


def seg_dist(px, py, a, b):
    ax, ay = a
    bx, by = b
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def coverage(x, y):
    inside = 0
    for sy in range(SS):
        for sx in range(SS):
            px, py = x + (sx + 0.5) / SS, y + (sy + 0.5) / SS
            if min(seg_dist(px, py, PATH[i], PATH[i + 1]) for i in range(len(PATH) - 1)) <= R:
                inside += 1
    return round(255 * inside / (SS * SS))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip().splitlines()[-1].strip())
    px = [[coverage(x, y) for x in range(W)] for y in range(H)]
    for row in px:
        print("".join(" .:-=+*#%@"[min(9, v * 10 // 256)] for v in row))
    with open(sys.argv[1], "w") as f:
        f.write("/* Generated by tools/icons/bt_rune.py: do not edit. */\n")
        f.write("#define BT_RUNE_W %d\n#define BT_RUNE_H %d\n" % (W, H))
        f.write("/* A8, row by row: coverage of the rune */\n")
        f.write("static const unsigned char BT_RUNE[BT_RUNE_W * BT_RUNE_H] = {\n")
        for row in px:
            f.write("    " + ", ".join("%3d" % v for v in row) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
