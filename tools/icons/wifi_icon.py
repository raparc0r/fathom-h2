"""
The header's Wi-Fi icon: a dot and three arcs (a 90 degree fan), anti-aliased, as
an A8 image the UI tints with the theme's colour. Sized like the header's other
symbols (Montserrat 14: a 16 px line, 13 px tall from 1 px below the baseline):
see bt_rune.py.

    python3 tools/icons/wifi_icon.py app/ui/wifi_icon.h      (and prints a preview)
"""
import math
import sys

W, H = 17, 16
CX, CY = W / 2, 12.9           # the fan's centre: the dot
R = 0.8                        # half the stroke width
RADII = (4.0, 7.0, 10.0)       # the arcs
HALF = math.radians(45)        # a 90 degree fan, pointing up
SS = 8


def inside(px, py):
    dx, dy = px - CX, CY - py
    d = math.hypot(dx, dy)
    if d <= 1.7:
        return True                                    # the dot
    ang = math.atan2(dx, dy)                           # 0 = straight up
    for r in RADII:
        if abs(d - r) <= R:
            if abs(ang) <= HALF:
                return True
            # round the arcs' ends
            for s in (-1, 1):
                ex, ey = CX + r * math.sin(s * HALF), CY - r * math.cos(s * HALF)
                if math.hypot(px - ex, py - ey) <= R:
                    return True
    return False


def coverage(x, y):
    n = sum(inside(x + (i + 0.5) / SS, y + (j + 0.5) / SS) for j in range(SS) for i in range(SS))
    return round(255 * n / (SS * SS))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip().splitlines()[-1].strip())
    px = [[coverage(x, y) for x in range(W)] for y in range(H)]
    for row in px:
        print("".join(" .:-=+*#%@"[min(9, v * 10 // 256)] for v in row))
    with open(sys.argv[1], "w") as f:
        f.write("/* Generated by tools/icons/wifi_icon.py: do not edit. */\n")
        f.write("#define WIFI_ICON_W %d\n#define WIFI_ICON_H %d\n" % (W, H))
        f.write("static const unsigned char WIFI_ICON[WIFI_ICON_W * WIFI_ICON_H] = {\n")
        for row in px:
            f.write("    " + ", ".join("%3d" % v for v in row) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
